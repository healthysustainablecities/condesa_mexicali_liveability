"""Export the controlled vocabularies to YAML for non-Python readers.

``uli/vocab.py`` is the single source of truth; this writes a readable
copy to ``schema/controlled_vocabularies.yml`` so that collaborators
working in R, QGIS or Excel can see the permitted terms without
reading python.  Re-run after any change to ``vocab.py``.
"""

import os
import sys

import yaml

HERE = os.path.dirname(os.path.abspath(__file__))
PROJECT_DIR = os.path.dirname(HERE)
sys.path.insert(0, PROJECT_DIR)

from uli import vocab  # noqa: E402

TARGET = os.path.join(
    PROJECT_DIR, 'schema', 'controlled_vocabularies.yml'
)


def main():
    document = {
        'schema_version': vocab.SCHEMA_VERSION,
        'generated_from': 'uli/vocab.py',
        'project_crs': {
            'code': vocab.PROJECT_CRS,
            'name': vocab.PROJECT_CRS_NAME,
        },
        'geo_levels': dict(vocab.GEO_LEVELS),
        'required_geo_levels': list(vocab.REQUIRED_GEO_LEVELS),
        'optional_geo_levels': list(vocab.OPTIONAL_GEO_LEVELS),
        'geo_resolution_order_coarse_to_fine': list(
            vocab.GEO_RESOLUTION_ORDER
        ),
        'lenses': dict(vocab.LENSES),
        'lenses_delivered_by_analysts': list(vocab.ANALYST_LENSES),
        'value_types': dict(vocab.VALUE_TYPES),
        'directions': dict(vocab.DIRECTIONS),
        'aggregation_methods': dict(vocab.AGGREGATION_METHODS),
        'quality_flags': dict(vocab.QUALITY_FLAGS),
        'denominator_types': dict(vocab.DENOMINATOR_TYPES),
        'evidence_types': dict(vocab.EVIDENCE_TYPES),
        'health_pathways': dict(vocab.HEALTH_PATHWAYS),
        'default_distance_thresholds_m': list(
            vocab.DISTANCE_THRESHOLDS_M
        ),
        'accessibility_bands_m': [
            list(band) for band in vocab.ACCESSIBILITY_BANDS_M
        ],
        'result_columns': {
            column: vocab.RESULT_COLUMN_DESCRIPTIONS[column]
            for column in vocab.RESULT_COLUMNS
        },
        'licence_hints': list(vocab.LICENCE_HINTS),
    }
    with open(TARGET, 'w', encoding='utf-8') as f:
        f.write(
            '# Generated by build/export_vocabularies.py -- do not '
            'edit by hand.\n'
            '# The authoritative definitions live in uli/vocab.py.\n'
        )
        yaml.safe_dump(
            document,
            f,
            sort_keys=False,
            allow_unicode=True,
            default_flow_style=False,
            width=72,
        )
    print(f'Written {TARGET}')


if __name__ == '__main__':
    main()
